function readPublicAsset(path) {
  return readFileSync(resolve(publicRoot, path), "utf8").replace(/\r\n/g, "\n").trimEnd();
}

function banner(kind) {
  return [
    `/* Generated by scripts/build-frontend-assets.mjs.`,
    `   Source ${kind} files remain under public/${kind === "JavaScript" ? "js" : "css"}/. */`,
    "",
  ].join("\n");
}

function writeAsset(path, contents) {
  const target = resolve(publicRoot, path);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, `${contents.trimEnd()}\n`);
}

function assetHash(contents) {
  return createHash("sha256").update(contents).digest("hex").slice(0, 12);
}

function updateHtmlAssetRefs(path, { jsFile, cssFile }) {
  const target = resolve(repoRoot, path);
  const isRootHtml = path === "index.html";
  const prefix = isRootHtml ? "public/" : "";
  const html = readFileSync(target, "utf8");
  const updated = html
    .replace(/href="(?:public\/)?(?:styles\.css|dist\/styles\.[a-f0-9]+\.css)"/, `href="${prefix}${cssFile}"`)
    .replace(/<script(?: type="module")? src="(?:public\/)?(?:app\.js|dist\/app\.[a-f0-9]+\.js)"><\/script>/, `<script src="${prefix}${jsFile}"></script>`);
  writeFileSync(target, updated);
}

const bundledJs = [
  banner("JavaScript"),
  ...jsChunks.map((chunk) => `\n/* ${chunk} */\n${readPublicAsset(chunk)}`),
].join("\n");

const bundledCss = [
  banner("CSS"),
  ...cssChunks.map((chunk) => `\n/* ${chunk} */\n${readPublicAsset(chunk)}`),
].join("\n");

const jsFile = `dist/app.${assetHash(bundledJs)}.js`;
const cssFile = `dist/styles.${assetHash(bundledCss)}.css`;

rmSync(resolve(publicRoot, "dist"), { recursive: true, force: true });
rmSync(resolve(publicRoot, "vendor"), { recursive: true, force: true });
mkdirSync(resolve(publicRoot, "vendor"), { recursive: true });
copyFileSync(resolve(repoRoot, "node_modules/csv-parse/dist/iife/sync.js"), resolve(publicRoot, "vendor/csv-parse-sync.js"));
copyFileSync(resolve(repoRoot, "node_modules/jszip/dist/jszip.min.js"), resolve(publicRoot, "vendor/jszip.min.js"));
copyFileSync(resolve(repoRoot, "node_modules/read-excel-file/bundle/read-excel-file.min.js"), resolve(publicRoot, "vendor/read-excel-file.min.js"));
copyFileSync(resolve(repoRoot, "node_modules/write-excel-file/bundle/write-excel-file.min.js"), resolve(publicRoot, "vendor/write-excel-file.min.js"));
writeAsset(jsFile, bundledJs);
writeAsset(cssFile, bundledCss);
writeAsset("app.js", bundledJs);
writeAsset("styles.css", bundledCss);
updateHtmlAssetRefs("index.html", { jsFile, cssFile });
updateHtmlAssetRefs("public/index.html", { jsFile, cssFile });

console.log(`Built public/app.js from ${jsChunks.length} JavaScript chunks.`);
